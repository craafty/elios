use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const FONT: &str = "font/eli-8x16.txt";
const GLYPH_WIDTH: usize = 8;
const GLYPH_HEIGHT: usize = 16;

fn main() {
    let dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    println!("cargo::rustc-link-arg-bins=-T{dir}/linker.ld");
    println!("cargo::rerun-if-changed=linker.ld");
    println!("cargo::rerun-if-changed={FONT}");

    let source = fs::read_to_string(Path::new(&dir).join(FONT)).unwrap();
    let font = parse_font(&source).unwrap_or_else(|(line, message)| panic!("{FONT}:{line}: {message}"));
    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("font.rs");
    fs::write(out, generate(&font)).unwrap();
}

type Glyph = [u8; GLYPH_HEIGHT];

struct Font {
    fallback: Glyph,
    glyphs: BTreeMap<char, Glyph>,
}

/// Parses the font's ASCII-art format (described at the top of the file).
/// Errors carry the 1-based line number.
fn parse_font(source: &str) -> Result<Font, (usize, String)> {
    let mut lines = source.lines().enumerate().map(|(i, line)| (i + 1, line.trim_end()));
    let mut fallback = None;
    let mut glyphs = BTreeMap::new();

    while let Some((number, line)) = lines.next() {
        if line.is_empty() || line.starts_with(';') {
            continue;
        }
        let name = line.strip_prefix("glyph ").ok_or((number, format!("expected `glyph`, found `{line}`")))?;
        let key = name.split_whitespace().next().unwrap_or("");
        let target = if key == "fallback" {
            None
        } else {
            let code = key
                .strip_prefix("U+")
                .and_then(|hex| u32::from_str_radix(hex, 16).ok())
                .and_then(char::from_u32)
                .ok_or((number, format!("expected `fallback` or a code point like U+0041, found `{key}`")))?;
            Some(code)
        };

        let mut glyph = [0u8; GLYPH_HEIGHT];
        for row in &mut glyph {
            let (number, line) = lines.next().ok_or((number, "glyph is missing rows".into()))?;
            if line.len() != GLYPH_WIDTH {
                return Err((number, format!("rows must be {GLYPH_WIDTH} pixels wide")));
            }
            for (column, pixel) in line.chars().enumerate() {
                match pixel {
                    '#' => *row |= 0x80 >> column,
                    '.' => {}
                    _ => return Err((number, format!("unexpected `{pixel}`; use `#` and `.`"))),
                }
            }
        }

        let duplicate = match target {
            None => fallback.replace(glyph).is_some(),
            Some(c) => glyphs.insert(c, glyph).is_some(),
        };
        if duplicate {
            return Err((number, "glyph defined twice".into()));
        }
    }

    let fallback = fallback.ok_or((0, "font has no `glyph fallback`".into()))?;
    Ok(Font { fallback, glyphs })
}

fn generate(font: &Font) -> String {
    let mut out = String::from("// Generated by build.rs from font/eli-8x16.txt.\n\n");
    writeln!(out, "pub static FALLBACK: [u8; {GLYPH_HEIGHT}] = {:?};\n", font.fallback).unwrap();

    out.push_str("/// Indexed by code point; characters the font lacks get the fallback.\n");
    writeln!(out, "static ASCII: [[u8; {GLYPH_HEIGHT}]; 128] = [").unwrap();
    for code in 0..128u8 {
        let glyph = font.glyphs.get(&char::from(code)).unwrap_or(&font.fallback);
        writeln!(out, "    {glyph:?},").unwrap();
    }
    out.push_str("];\n\n");

    out.push_str("/// Everything beyond ASCII, sorted for binary search.\n");
    let extra: Vec<_> = font.glyphs.iter().filter(|(c, _)| !c.is_ascii()).collect();
    writeln!(out, "static EXTRA: [(char, [u8; {GLYPH_HEIGHT}]); {}] = [", extra.len()).unwrap();
    for (c, glyph) in extra {
        writeln!(out, "    ({c:?}, {glyph:?}),").unwrap();
    }
    out.push_str("];\n");
    out
}
