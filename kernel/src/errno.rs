//! Error numbers, as defined by the Linux system call ABI (which eliOS
//! implements). System calls return them negated.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(i64)]
#[allow(dead_code, reason = "the full set, for system calls to come")]
#[allow(clippy::upper_case_acronyms, reason = "the names Linux and C use")]
pub enum Errno {
    EPERM = 1,
    ENOENT = 2,
    ESRCH = 3,
    EINTR = 4,
    EIO = 5,
    ENXIO = 6,
    E2BIG = 7,
    ENOEXEC = 8,
    EBADF = 9,
    ECHILD = 10,
    EAGAIN = 11,
    ENOMEM = 12,
    EACCES = 13,
    EFAULT = 14,
    EBUSY = 16,
    EEXIST = 17,
    EXDEV = 18,
    ENODEV = 19,
    ENOTDIR = 20,
    EISDIR = 21,
    EINVAL = 22,
    ENFILE = 23,
    EMFILE = 24,
    ENOTTY = 25,
    EFBIG = 27,
    ENOSPC = 28,
    ESPIPE = 29,
    EROFS = 30,
    EMLINK = 31,
    EPIPE = 32,
    ERANGE = 34,
    ENAMETOOLONG = 36,
    ENOSYS = 38,
    ENOTEMPTY = 39,
    ELOOP = 40,
    ENOTSOCK = 88,
    EDESTADDRREQ = 89,
    EMSGSIZE = 90,
    EPROTOTYPE = 91,
    ENOPROTOOPT = 92,
    EPROTONOSUPPORT = 93,
    EOPNOTSUPP = 95,
    EAFNOSUPPORT = 97,
    EADDRINUSE = 98,
    EADDRNOTAVAIL = 99,
    ENETDOWN = 100,
    ENETUNREACH = 101,
    ECONNABORTED = 103,
    ECONNRESET = 104,
    ENOBUFS = 105,
    EISCONN = 106,
    ENOTCONN = 107,
    ETIMEDOUT = 110,
    ECONNREFUSED = 111,
    EHOSTUNREACH = 113,
    EALREADY = 114,
    EINPROGRESS = 115,
}

pub type Result<T> = core::result::Result<T, Errno>;

/// The symbolic name of an error number, for tracing.
pub fn name(errno: i64) -> &'static str {
    const NAMES: [&str; 41] = [
        "0",
        "EPERM",
        "ENOENT",
        "ESRCH",
        "EINTR",
        "EIO",
        "ENXIO",
        "E2BIG",
        "ENOEXEC",
        "EBADF",
        "ECHILD",
        "EAGAIN",
        "ENOMEM",
        "EACCES",
        "EFAULT",
        "ENOTBLK",
        "EBUSY",
        "EEXIST",
        "EXDEV",
        "ENODEV",
        "ENOTDIR",
        "EISDIR",
        "EINVAL",
        "ENFILE",
        "EMFILE",
        "ENOTTY",
        "ETXTBSY",
        "EFBIG",
        "ENOSPC",
        "ESPIPE",
        "EROFS",
        "EMLINK",
        "EPIPE",
        "EDOM",
        "ERANGE",
        "EDEADLK",
        "ENAMETOOLONG",
        "ENOLCK",
        "ENOSYS",
        "ENOTEMPTY",
        "ELOOP",
    ];
    if let Some(name) = NAMES.get(errno as usize) {
        return name;
    }
    match errno {
        88 => "ENOTSOCK",
        89 => "EDESTADDRREQ",
        90 => "EMSGSIZE",
        91 => "EPROTOTYPE",
        92 => "ENOPROTOOPT",
        93 => "EPROTONOSUPPORT",
        95 => "EOPNOTSUPP",
        97 => "EAFNOSUPPORT",
        98 => "EADDRINUSE",
        99 => "EADDRNOTAVAIL",
        100 => "ENETDOWN",
        101 => "ENETUNREACH",
        103 => "ECONNABORTED",
        104 => "ECONNRESET",
        105 => "ENOBUFS",
        106 => "EISCONN",
        107 => "ENOTCONN",
        110 => "ETIMEDOUT",
        111 => "ECONNREFUSED",
        113 => "EHOSTUNREACH",
        114 => "EALREADY",
        115 => "EINPROGRESS",
        _ => "E?",
    }
}
